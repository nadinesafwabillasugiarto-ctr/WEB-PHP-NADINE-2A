<?php
//  OPERATOR PENUGASAN
//  Operator penugasan digunakan untuk menetapkan nilai ke variabel. Operator penugasan yang umum digunakan antara lain:

$kecepatan = 44;
 
// ini opertor aritmatika
$kecepatan = $kecepatan + 14;
 
// maka nilai kecepatan akan sama dengan 44 + 14 = 58
 
// ini operator penugasan
$kecepatan += 10;
 
// sekarang nilai kecepatan akan menjadi 58 + 10 = 68
 
echo "nilai kecepatan adalah $kecepatan";
 
?>