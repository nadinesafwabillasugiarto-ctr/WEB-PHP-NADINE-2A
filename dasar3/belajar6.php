<?php
// OPERATOR ARITMATIKA
// Operator aritmatika digunakan untuk melakukan operasi matematika pada nilai numerik. Operator aritmatika yang umum digunakan antara lain:

$x = 4;
$y = 4;
 
// penjumlahan
$z = $x + $y;
echo "$x + $y = $z";
echo "<br>";
 
// pengurangan
$z = $x - $y;
echo "$x - $y = $z";
echo "<br>";
 
// Perkalian
$z = $x * $y;
echo "$x * $y = $z";
echo "<br>";
 
// Pembagian
$z = $x / $y;
echo "$x / $y = $z";
echo "<br>";
 
// Sisa bagi
$z = $x % $y;
echo "$x % $y = $z";
echo "<br>";
 
// Pangkat
$z = $x ** $y;
echo "$x ** $y = $z";
echo "<br>";
 
?>