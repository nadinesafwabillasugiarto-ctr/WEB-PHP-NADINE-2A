<?php
// OPERATOR INCREMENT & DECREMENT
// Operator Increment & Decrement diguanakan untuk menambah +1 (tambah satu) dan mengurangi -1 (kurangi dengan satu). 
 
$score = 0;
 
$score++;
$score++;
$score++; 
 
//nilanya bertambah 3
echo '<br> nilai $score sekarang='.$score; //3
 
$score--;
$score--;
 
//nilainya berkurang 2
echo '<br> nilai $score sekarang='.$score; //1
 
?>