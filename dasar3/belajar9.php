<?php
// OPERATOR PEMBANDING
// Operator Pembanding digunakan untuk membandingkan dua buah nilai.
 
$x = 6;
$y = 8;
 
// menggunakan operator pembanding lebih besar
$z = $x > $y;
echo "$x > $y: $z";
echo "<br>";
 
// menggunakan operator pembanding lebih kecil
$z = $x < $y;
echo "$x < $y: $z";
echo "<br>";
 
// menggunakan operator pembanding lebih sama dengan
$z = $x == $y;
echo "$x == $y: $z";
echo "<br>";
 
// menggunakan operator pembanding lebih tidak sama dengan
$z = $x != $y;
echo "$x != $y: $z";
echo "<br>";
 
// menggunakan operator pembanding lebih besar sama dengan
$z = $x >= $y;
echo "$x >= $y: $z";
echo "<br>";
 
// menggunakan operator pembanding lebih kecil sama dengan
$z = $x <= $y;
echo "$x <= $y: $z";
echo "<br>";
 
?>